/* ---- 帧率档位（详见 THROUGHPUT_PROBE.md）-----------------------------------
 * 帧率 = PCLK / (HTS x VTS)。原表 HTS=1896、VTS=984、实测 30.0 fps
 *   => PCLK = 1896 * 984 * 30.0 = **56.0 MHz**（不是从 0x4837 估的 58.8）。
 * 抬 PLL 就是按比例抬 PCLK，实测与模型吻合到 1% 以内。
 *
 * fps 的算法：先量网卡线速，再除以**每帧线上字节数 8.072 Mbit**（960000 负载
 * + 700*24 包头 + 700*46 的 UDP/IP/以太网开销）。别用仅负载的 7.68 Mbit/帧，
 * 那会把帧率报高约 5%。档位 8 另有直接点名计数：575 帧 / 11.94 s = 48.1 fps。
 *
 * **全部档位已上板实测（2026-10-02）**：
 *
 *   档位 0 = 原表 HTS=1896 VTS=984 PLL=0x46   -> 30.0 fps ✅（原基线）
 *   档位 1 = HTS=1600                          -> ❌ 无帧
 *   档位 2 = HTS=1400                          -> ❌ 无帧
 *   档位 3 = HTS=1200                          -> ❌ 无帧
 *   档位 4 = VTS=768                           -> ❌ 无帧
 *   档位 5 = HTS=1600 + VTS=900                -> ❌ 无帧
 *   档位 6 = PLL 0x3036=0x54 (PCLK ≈ 67.2MHz)  -> 36 fps ✅
 *   档位 7 = PLL 0x3036=0x60 (PCLK ≈ 76.8MHz)  -> 41 fps ✅ 画面正常
 *   档位 8 = PLL 0x3036=0x70 (PCLK ≈ 89.6MHz)  -> **48 fps** ✅ 默认（实测 48.1）
 *   档位 9 = PLL 0x3036=0x80 (PCLK ≈102.4MHz)  -> **55 fps** ✅ 画面正常 = 实测上限
 *   档位 10= PLL 0x3036=0xa0                   -> 44 fps ↓（不升反降）
 *   档位 11= PLL 0x3036=0xb0                   -> 38 fps ↓
 *
 * **两条结论**
 *   1. 提帧率要抬 PLL（PCLK），**不要动 HTS/VTS** —— 档位 1~5 全部让传感器彻底不出图
 *      （camera_init 成功、无 VDMA halt、但 VDMA 一个帧缓冲都没被写）。
 *      追加写和就地改值两种写法都试过，结果相同，所以不是"重复写寄存器"引起的。
 *   2. 抬 PLL 的效果与 `fps = PCLK/(HTS*VTS)` 吻合到 1% 以内，**一直到档位 9 为止**；
 *      再往上（10/11）帧率反而下降 —— 传感器 DVP 在 PCLK ≈ 100 MHz 左右到顶。
 *
 * 代价：PCLK 越高，同一曝光行数对应的曝光时间越短（图更暗、AEC 靠增益补偿），
 * 但运动模糊更小 —— 对运动的二维码是有利的。档位 8 的线上码率 ≈ 391 Mbit/s，
 * 实测链路能到 817 Mbit/s，余量充足。
 *
 * 注意 PCLK 一变，**0x4837（PCLK 周期提示值）必须跟着改**，否则 DVP 时序不匹配。
 * 位流里 `create_clock cam1_pclk -period 10.000`（100 MHz）——档位 8（89.6MHz）在其内；
 * 档位 9（102.4MHz）略超出，实测硬件上是通的，但长期用应改约束并重跑实现。
 *
 * **分辨率**：本板 800x600 可用；1024x576(HD) 与 640x480 **实测采不到帧**——
 * 2026-10-02 用 ov5640_1 自己的 HD 位流+应用做 A/B，S2MM SR 恒为 0、无帧完成，
 * 与本工程表现一致。换分辨率必须整表下发（PLL + 输出尺寸 + 裁剪窗口 +
 * 0x3814/0x3815 + HTS/VTS + 0x4837 一起），并上板验证。
 *
 * 这些寄存器**必须写在 stream-on(0x3008=0x02) 之前**：实测流启动后再写，
 * AXI IIC 的 XIic_Send 会返回 0/1（失败），继续访问还会把应用卡死。 */
/* 帧率档位由视频档位（ethernet_config.h 的 VIDEO_PROFILE）决定，
 * 也可用 -DOV5640_FAST_TIMING=n 单独特调（做实验时用）。
 * 档位必须与 VIDEO_WIDTH/HEIGHT 属于同一份传感器表，否则几何会错。 */
